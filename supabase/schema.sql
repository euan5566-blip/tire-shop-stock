create or replace view public.daily_profit_summary as
select date(s.created_at) as sale_date,
 count(distinct s.id) as orders,
 coalesce(sum(s.total),0) as sales,
 coalesce(sum(si.cost*si.qty),0) as cost,
 coalesce(sum(si.profit),0) as gross_profit
from public.sales s left join public.sale_items si on si.sale_id=s.id
group by date(s.created_at) order by sale_date desc;

