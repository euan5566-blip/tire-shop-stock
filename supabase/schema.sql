create or replace function public.create_sale_v2(p_invoice_no text,p_customer_id bigint,p_car_id bigint,p_discount numeric,p_paid numeric,p_currency text,p_items jsonb)returns uuid language plpgsql security definer set search_path=public as $$
declare v_sale uuid;v_sub numeric:=0;v_total numeric;it jsonb;p public.products%rowtype;q numeric;v_price numeric;v_cost numeric;v_rate numeric:=1;
begin
 if p_currency not in('THB','LAK','USD') then raise exception 'สกุลเงินไม่ถูกต้อง'; end if;
 for it in select * from jsonb_array_elements(p_items) loop
  select * into p from public.products where id=(it->>'product_id')::uuid for update;
  q=(it->>'qty')::numeric; v_price=coalesce((it->>'price')::numeric,p.price); v_cost=coalesce((it->>'cost')::numeric,p.cost);
  if p.id is null or p.stock<q then raise exception 'สินค้าไม่พอในสต็อก'; end if;
  v_sub:=v_sub+v_price*q;
 end loop;
 v_total=greatest(v_sub-coalesce(p_discount,0),0);
 insert into public.sales(invoice_no,customer_id,car_id,subtotal,discount,total,paid,change,sold_by,currency,exchange_rate) values(p_invoice_no,p_customer_id,p_car_id,v_sub,coalesce(p_discount,0),v_total,coalesce(p_paid,0),greatest(coalesce(p_paid,0)-v_total,0),auth.uid(),p_currency,1) returning id into v_sale;
 for it in select * from jsonb_array_elements(p_items) loop
  select * into p from public.products where id=(it->>'product_id')::uuid for update; q=(it->>'qty')::numeric; v_price=coalesce((it->>'price')::numeric,p.price); v_cost=coalesce((it->>'cost')::numeric,p.cost);
  insert into public.sale_items(sale_id,product_id,qty,cost,price) values(v_sale,p.id,q,v_cost,v_price);
  update public.products set stock=stock-q,updated_at=now() where id=p.id;
  insert into public.stock_movements(product_id,qty,movement_type,ref_id,created_by,note) values(p.id,-q,'out',v_sale,auth.uid(),'ขายสินค้า');
 end loop;
 return v_sale;
end$$;

-- Keep employee email synchronized for new users and make the first created profile the owner only when no owner exists.
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,full_name,email,role) values(new.id,coalesce(new.raw_user_meta_data->>'full_name',''),new.email,case when not exists(select 1 from public.profiles where role='owner') then 'owner' else 'staff' end)
 on conflict(id) do update set email=excluded.email;
 return new;
end$$;
