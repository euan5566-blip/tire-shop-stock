create or replace function public.create_sale(p_invoice_no text,p_customer_id bigint,p_car_id bigint,p_discount numeric,p_paid numeric,p_items jsonb)returns uuid language plpgsql security definer set search_path=public as $$
declare v_sale uuid;v_sub numeric:=0;v_total numeric;it jsonb;p public.products%rowtype;q numeric;
begin
for it in select * from jsonb_array_elements(p_items) loop select * into p from public.products where id=(it->>'product_id')::uuid for update;q=(it->>'qty')::numeric;if p.id is null or p.stock<q then raise exception 'สินค้าไม่พอในสต็อก';end if;v_sub:=v_sub+p.price*q;end loop;
v_total=greatest(v_sub-coalesce(p_discount,0),0);
insert into public.sales(invoice_no,customer_id,car_id,subtotal,discount,total,paid,change,sold_by)values(p_invoice_no,p_customer_id,p_car_id,v_sub,coalesce(p_discount,0),v_total,coalesce(p_paid,0),greatest(coalesce(p_paid,0)-v_total,0),auth.uid())returning id into v_sale;
for it in select * from jsonb_array_elements(p_items) loop select * into p from public.products where id=(it->>'product_id')::uuid for update;q=(it->>'qty')::numeric;insert into public.sale_items(sale_id,product_id,qty,cost,price)values(v_sale,p.id,q,p.cost,p.price);update public.products set stock=stock-q,updated_at=now()where id=p.id;insert into public.stock_movements(product_id,qty,movement_type,ref_id,created_by,note)values(p.id,-q,'out',v_sale,auth.uid(),'ขายสินค้า');end loop;return v_sale;end$$;
create or replace function public.receive_stock(p_product_id uuid,p_qty numeric,p_note text default null)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_id uuid;
begin
 if p_qty<=0 then raise exception 'จำนวนต้องมากกว่า 0'; end if;
 update public.products set stock=stock+p_qty,updated_at=now() where id=p_product_id returning id into v_id;
 if v_id is null then raise exception 'ไม่พบสินค้า'; end if;
 insert into public.stock_movements(product_id,qty,movement_type,created_by,note) values(p_product_id,p_qty,'in',auth.uid(),coalesce(p_note,'รับสินค้าเข้า'));
 return v_id;
end$$;

